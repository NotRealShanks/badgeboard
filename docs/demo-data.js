// Generates a large synthetic dataset with N participants for performance and pagination testing
export function generateLargeDemoDataset(count = 250) {
  const firstNames = ["Aria", "Bram", "Cora", "Dax", "Elena", "Finn", "Gala", "Hugo", "Isla", "Jarek", "Kira", "Leo", "Maren", "Nico", "Orla", "Pike", "Quinn", "Rowan", "Soren", "Tess"];
  const lastNames = ["Arden", "Bexley", "Corvus", "Dunmore", "Eldridge", "Fallow", "Gresham", "Hollis", "Ingram", "Jansen", "Ketter", "Lowell", "Mercer", "Nash", "Oakes", "Perrin", "Quill", "Rook", "Stratton", "Vance"];

  const results = [];
  const unreachable = [];
  let completeCount = 0;
  let inProgressCount = 0;
  let noBadgesCount = 0;

  for (let i = 1; i <= count; i++) {
    const fn = firstNames[i % firstNames.length];
    const ln = lastNames[(i * 3) % lastNames.length];
    const name = `${fn} ${ln} ${i}`;
    const hex = i.toString(16).padStart(4, "0").toUpperCase();
    const uuid = `22222222-0000-4000-8000-${i.toString(16).padStart(12, "0")}`;
    const profileUrl = `https://www.skills.google/public_profiles/${uuid}`;

    const mod = i % 10;
    if (mod === 9) {
      // Unreachable
      unreachable.push({
        id: `large-${i}`,
        student: { name, profile_url: profileUrl, uuid },
        display_name: name,
        pseudonym: `Learner-${hex}`,
        status: i % 2 === 0 ? "private_or_not_found" : "network_error",
        reason: i % 2 === 0 ? "Profile set to private" : "DNS lookup timeout",
        retryable: i % 2 !== 0
      });
    } else if (mod <= 3) {
      // Complete (10 badges)
      completeCount++;
      results.push({
        id: `large-${i}`,
        student: { name, profile_url: profileUrl, uuid },
        display_name: name,
        pseudonym: `Learner-${hex}`,
        status: "complete",
        counted_badges: 10,
        total_badges: 10,
        goal: 10,
        last_badge_date: "2026-11-04",
        league: "Silver League",
        points: 350,
        badges: [
          { title: "Develop GenAI Apps with Gemini and Streamlit", earned_at: "2026-11-04" },
          { title: "Prompt Design in Vertex AI", earned_at: "2026-11-02" }
        ]
      });
    } else if (mod <= 7) {
      // In progress
      inProgressCount++;
      const badgesCount = (i % 9) + 1;
      results.push({
        id: `large-${i}`,
        student: { name, profile_url: profileUrl, uuid },
        display_name: name,
        pseudonym: `Learner-${hex}`,
        status: "in_progress",
        counted_badges: badgesCount,
        total_badges: badgesCount,
        goal: 10,
        last_badge_date: "2026-10-25",
        league: "Bronze League",
        points: badgesCount * 35,
        badges: [
          { title: "Develop GenAI Apps with Gemini and Streamlit", earned_at: "2026-10-25" }
        ]
      });
    } else {
      // No badges
      noBadgesCount++;
      results.push({
        id: `large-${i}`,
        student: { name, profile_url: profileUrl, uuid },
        display_name: name,
        pseudonym: `Learner-${hex}`,
        status: "no_badges",
        counted_badges: 0,
        total_badges: 0,
        goal: 10,
        last_badge_date: "",
        league: "",
        points: 0,
        badges: []
      });
    }
  }

  return {
    summary: {
      goal: 10,
      total_students: count,
      complete_count: completeCount,
      in_progress_count: inProgressCount,
      no_badges_count: noBadgesCount,
      unreachable_count: unreachable.length,
      network_requests: count - 25,
      cache_hits: 25,
      retries: 3,
      rate_limit_pause_seconds: 4.1,
      duration_seconds: 45.2,
      bad_rows_count: 0
    },
    results,
    unreachable
  };
}

